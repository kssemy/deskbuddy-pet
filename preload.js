const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('pet', {
  load: () => ipcRenderer.invoke('load'),
  historyMonth: (year, month) => ipcRenderer.invoke('history-month', year, month),
  openHistory: () => ipcRenderer.send('open-history'),
  openWardrobe: () => ipcRenderer.send('open-wardrobe'),
  activateCharacter: id => ipcRenderer.invoke('activate-character', id),
  deleteCharacter: id => ipcRenderer.invoke('delete-character', id),
  checkUpdate: () => ipcRenderer.invoke('check-update'),
  installUpdate: () => ipcRenderer.invoke('install-update'),
  applyAvailableUpdate: () => ipcRenderer.invoke('apply-available-update'),
  dismissUpdate: () => ipcRenderer.send('dismiss-update'),
  openRelease: () => ipcRenderer.send('open-release'),
  chooseImage: () => ipcRenderer.invoke('choose-image'),
  saveAiKey: key => ipcRenderer.invoke('save-ai-key', key),
  generateAiPose: action => ipcRenderer.invoke('generate-ai-pose', action),
  registerAiPose: (action, images) => ipcRenderer.invoke('register-ai-pose', action, images),
  removePoseSet: id => ipcRenderer.invoke('remove-pose-set', id),
  removePose: name => ipcRenderer.invoke('remove-pose', name),
  resizePanel: height => ipcRenderer.send('resize-panel', height),
  connectPet: (name, pin, register) => ipcRenderer.invoke('connect-pet', name, pin, register),
  disconnectPet: () => ipcRenderer.invoke('disconnect-pet'),
  onRemote: callback => ipcRenderer.on('remote-update', (_event, data) => callback(data)),
  onRemotePoses: callback => ipcRenderer.on('remote-poses', (_event, poses) => callback(poses)),
  onRemoteSize: callback => ipcRenderer.on('remote-size', (_event, size) => callback(size)),
  setSize: value => ipcRenderer.invoke('set-size', value),
  setOpacity: value => ipcRenderer.invoke('set-opacity', value),
  setTasks: tasks => ipcRenderer.invoke('set-tasks', tasks),
  setShareTodos: value => ipcRenderer.invoke('set-share-todos', value),
  setMemos: memos => ipcRenderer.invoke('set-memos', memos),
  setSettings: settings => ipcRenderer.invoke('set-settings', settings),
  setSpeech: (text, temporary) => ipcRenderer.invoke('set-speech', text, temporary),
  togglePanel: () => ipcRenderer.send('toggle-panel'),
  toggleChat: () => ipcRenderer.send('toggle-chat'),
  drag: (dx, dy) => ipcRenderer.send('drag-pet', dx, dy),
  dragStart: () => ipcRenderer.send('drag-pet-start'),
  dragEnd: () => ipcRenderer.send('drag-pet-end'),
  remoteTodoBounds: bounds => ipcRenderer.send('remote-todo-bounds', bounds),
  remoteDragState: value => ipcRenderer.send('remote-drag-state', value),
  dragRemote: (dx, dy) => ipcRenderer.send('remote-drag', dx, dy),
  refreshTop: () => ipcRenderer.send('refresh-top'),
  arrangeHome: () => ipcRenderer.send('arrange-home'),
  glow: () => ipcRenderer.send('glow-pet'),
  pokeFriend: () => ipcRenderer.send('poke-friend'),
  onReaction: callback => { ipcRenderer.on('pet-reaction', (_event, value) => callback(value)); ipcRenderer.on('remote-reaction', (_event, value) => callback(value)); },
  hover: value => ipcRenderer.send('hover-pet', value),
  onChange: callback => ipcRenderer.on('data-changed', (_event, data) => callback(data))
});
